        appendDetailTable(detailRowsToTriples(model.methodRows))
        if (model.impactItems.isNotEmpty()) {
            appendLine("**Impact**")
            appendLine()
            appendImpactItems(impactItemsToStrings(model.impactItems))
        }
        if (model.references.isNotEmpty()) {
            appendLine("**References**")
            appendLine()
            model.references.forEach { ref -> appendLine("- $ref") }
            appendLine()
        }
        appendLine("---")
        appendLine()
    }

    private fun StringBuilder.appendDeviceInfo(model: DeviceInfoCardModel) {
        appendLine("### ${model.title}")
        appendLine()
        appendLine("> ${model.verdict}")
        appendLine()
        appendFactsTable(headerFactsToPairs(model.headerFacts))
        model.sections.forEach { section ->
            appendLine("**${section.title}**")
            appendLine()
            appendLine("| Key | Value |")
            appendLine("|-----|-------|")
            section.rows.forEach { row ->
                appendLine("| ${row.label} | ${row.value} |")
            }
            appendLine()
        }
    }
