    fun format(state: DashboardUiState): String = buildString {
        val now = SimpleDateFormat("yyyy-MM-dd HH:mm:ss (z)", Locale.US).format(Date())

        appendLine("# Duck Detector — Security Scan Report")
        appendLine()
        appendLine("| Item | Value |")
        appendLine("|------|-------|")
        appendLine("| App Version | ${BuildConfig.VERSION_NAME} (${BuildConfig.VERSION_CODE}) |")
        appendLine("| Build Hash | ${BuildConfig.BUILD_HASH} |")
        appendLine("| Build Time | ${formatBuildTimeUtc(BuildConfig.BUILD_TIME_UTC)} (UTC) |")
        appendLine("| Report Time | $now |")
        appendLine()

        appendLine("## Overview")
        appendLine()
        appendLine("> **${state.overview.headline}** — ${state.overview.summary}")
        appendLine()
        appendLine("| Danger | Warning | Ready | Pending |")
        appendLine("|--------|---------|-------|---------|")
        val danger = state.overview.metrics.find { it.label == "Danger" }?.value ?: "0"
        val warning = state.overview.metrics.find { it.label == "Warning" }?.value ?: "0"
        val ready = state.overview.metrics.find { it.label == "Ready" }?.value ?: "0"
        val pending = state.overview.metrics.find { it.label == "Pending" }?.value ?: "0"
        appendLine("| $danger | $warning | $ready | $pending |")
        appendLine()

        appendLine("## Detector Cards")
        appendLine()
        state.detectorCards.forEach { entry ->
            appendDetectorCard(entry)
        }

        appendLine("## Device Info")
        appendLine()
        appendDeviceInfo(state.deviceInfoCard)
        appendLine()

        appendLine("---")
        appendLine("*Report generated by Duck Detector v${BuildConfig.VERSION_NAME}*")
    }

    private fun StringBuilder.appendDetectorCard(entry: DashboardDetectorCardEntry) {
        when (entry) {
            is DashboardDetectorCardEntry.Bootloader -> appendBootloader(entry.model)
            is DashboardDetectorCardEntry.Mount -> appendMount(entry.model)
            is DashboardDetectorCardEntry.CustomRom -> appendCustomRom(entry.model)
            is DashboardDetectorCardEntry.Selinux -> appendSelinux(entry.model)
            is DashboardDetectorCardEntry.DangerousApps -> appendDangerousApps(entry.model)
            is DashboardDetectorCardEntry.KernelCheck -> appendKernelCheck(entry.model)
            is DashboardDetectorCardEntry.Memory -> appendMemory(entry.model)
            is DashboardDetectorCardEntry.LSPosed -> appendLSPosed(entry.model)
            is DashboardDetectorCardEntry.NativeRoot -> appendNativeRoot(entry.model)
            is DashboardDetectorCardEntry.PlayIntegrityFix -> appendPlayIntegrityFix(entry.model)
            is DashboardDetectorCardEntry.Tee -> appendTee(entry.model)
            is DashboardDetectorCardEntry.Su -> appendSu(entry.model)
            is DashboardDetectorCardEntry.SystemProperties -> appendSystemProperties(entry.model)
            is DashboardDetectorCardEntry.Virtualization -> appendVirtualization(entry.model)
            is DashboardDetectorCardEntry.Zygisk -> appendZygisk(entry.model)
        }
    }

    private val String.mdEscape: String get() = replace("|", "\\|").replace("\n", " ")

    private fun severityBadge(severity: DetectionSeverity): String = when (severity) {
        DetectionSeverity.DANGER -> "🔴 DANGER"
        DetectionSeverity.WARNING -> "🟡 WARNING"
        DetectionSeverity.INFO -> "🔵 INFO"
        DetectionSeverity.ALL_CLEAR -> "🟢 CLEAR"
    }

    private fun StringBuilder.appendCardHeader(
        title: String,
        verdict: String,
        severity: DetectionSeverity,
    ) {
        appendLine("### ${severityBadge(severity)} — $title")
        appendLine()
        appendLine("> **Verdict:** ${verdict.mdEscape}")
        appendLine()
    }

    private fun StringBuilder.appendFactsTable(facts: List<Pair<String, String>>) {
        if (facts.isEmpty()) return
        appendLine("| Key | Value |")
        appendLine("|-----|-------|")
        facts.forEach { (label, value) ->
            appendLine("| ${label.mdEscape} | ${value.mdEscape} |")
        }
        appendLine()
    }

    private fun StringBuilder.appendDetailTable(
        rows: List<Triple<String, String, String?>>,
    ) {
        if (rows.isEmpty()) return
        appendLine("| Item | Result | Detail |")
        appendLine("|------|--------|--------|")
        rows.forEach { (label, value, detail) ->
            val detailStr = if (!detail.isNullOrBlank() && detail != value) detail.mdEscape else ""
            appendLine("| ${label.mdEscape} | ${value.mdEscape} | $detailStr |")
        }
        appendLine()
    }

    private fun StringBuilder.appendImpactItems(items: List<String>) {
        if (items.isEmpty()) return
        items.forEach { text ->
            appendLine("- ${text.mdEscape}")
        }
        appendLine()
    }

    private fun headerFactsToPairs(facts: List<*>): List<Pair<String, String>> {
        return try {
            @Suppress("UNCHECKED_CAST")
            facts.map { fact ->
                val label =
                    fact!!::class.java.getDeclaredField("label").apply { isAccessible = true }.get(fact) as String
                val value =
                    fact!!::class.java.getDeclaredField("value").apply { isAccessible = true }.get(fact) as String
                label to value
            }
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun detailRowsToTriples(rows: List<*>): List<Triple<String, String, String?>> {
        return try {
            @Suppress("UNCHECKED_CAST")
            rows.map { row ->
                val label =
                    row!!::class.java.getDeclaredField("label").apply { isAccessible = true }.get(row) as String
                val value =
                    row!!::class.java.getDeclaredField("value").apply { isAccessible = true }.get(row) as String
                val detail = try {
                    row::class.java.getDeclaredField("detail").apply { isAccessible = true }.get(row) as? String
                } catch (_: Exception) {
                    null
                }
                Triple(label, value, detail)
            }
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun impactItemsToStrings(items: List<*>): List<String> {
        return try {
            @Suppress("UNCHECKED_CAST")
            items.map { item ->
                item!!::class.java.getDeclaredField("text").apply { isAccessible = true }.get(item) as String
            }
        } catch (_: Exception) {
            emptyList()
        }
    }

    private fun StringBuilder.appendSectionTitle(title: String, isEmpty: Boolean) {
        if (isEmpty) return
        appendLine("**$title**")
        appendLine()
    }

    private fun StringBuilder.appendBootloader(model: BootloaderCardModel) {
        appendCardHeader(model.title, model.verdict, model.status.severity)
        appendFactsTable(headerFactsToPairs(model.headerFacts))
        appendSectionTitle("State", model.stateRows.isEmpty())
        appendDetailTable(detailRowsToTriples(model.stateRows))
        appendSectionTitle("Attestation", model.attestationRows.isEmpty())
        appendDetailTable(detailRowsToTriples(model.attestationRows))
        appendSectionTitle("Properties", model.propertyRows.isEmpty())
        appendDetailTable(detailRowsToTriples(model.propertyRows))
        appendSectionTitle("Consistency", model.consistencyRows.isEmpty())
